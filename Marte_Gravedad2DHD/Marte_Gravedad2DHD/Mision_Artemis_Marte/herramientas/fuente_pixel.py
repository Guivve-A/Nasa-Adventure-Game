AGUDO = ["..#", ".#."]
# letras con tilde: base + marca encima
ACENTOS = {'á': ('a', 'agudo'), 'é': ('e', 'agudo'), 'í': ('ı', 'agudo'), 'ó': ('o', 'agudo'), 'ú': ('u', 'agudo'),
           'ñ': ('n', 'tilde'), 'ü': ('u', 'dieresis'),
           'Á': ('A', 'agudo'), 'É': ('E', 'agudo'), 'Í': ('I', 'agudo'), 'Ó': ('O', 'agudo'), 'Ú': ('U', 'agudo'),
           'Ñ': ('N', 'tilde'), 'Ü': ('U', 'dieresis')}
G['ı'] = [".", ".", "#", "#", "#", "#", "#"]


def celda(filas):
    """devuelve 11 filas: 2 de tilde + 9 (alto + descendente)"""
    w = len(filas[0])
    f = list(filas) + ["." * w] * (9 - len(filas))
    return ["." * w, "." * w] + f


def marca(tipo, w):
    if tipo == 'agudo':
        m = ["..#", ".#."] if w >= 3 else [".#", "#."]
    elif tipo == 'tilde':
        m = [".#.#", "#.#."] if w <= 4 else [".##.#", "#..#."]
    else:
        m = ["#..#", "...."] if w <= 4 else [".#.#.", "....."]
    pad = max(0, (w - len(m[0])) // 2 + (1 if tipo == 'agudo' and w >= 4 else 0))
    return [("." * pad + r).ljust(w, ".")[:max(w, len(r))] for r in m]


def construir():
    glifos = {}
    for ch, filas in G.items():
        glifos[ch] = celda(filas)
    for ch, (base, tipo) in ACENTOS.items():
        c = list(glifos[base])
        w = len(c[0])
        m = marca(tipo, w)
        w = max(w, len(m[0]))
        c = [r.ljust(w, ".") for r in c]
        if base.isupper():
            if tipo == 'tilde':
                c[0], c[1] = m[0].ljust(w, "."), m[1].ljust(w, ".")
            else:
                c[0] = (m[1] if tipo == 'agudo' else m[0]).ljust(w, ".")   # una sola fila y un espacio
                if tipo == 'agudo':
                    c[0] = ("." * (w // 2) + "##").ljust(w, ".")[:w]
        else:
            # deja una fila libre sobre la altura de x (fila 4)
            if tipo == 'dieresis':
                c[2] = m[0].ljust(w, ".")
            else:
                c[1], c[2] = m[0].ljust(w, "."), m[1].ljust(w, ".")
        glifos[ch] = c
    return glifos


